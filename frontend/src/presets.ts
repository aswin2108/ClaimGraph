import type { FNOL } from "./types";

// Synthetic FNOL scenarios for the intake card. They reference identifiers that already exist in
// the loaded graph, so every connection is discovered by real graph queries, never hardcoded into
// the UI. Each preset only fills the form; the investigator can edit any field before submitting.
//
// Two sets: one for the 20,000-claim book (graph claimgraph_scale, loaded by cmd/seedscale with its
// default seed) and one for the small curated graph (claimgraph, and the e2e scratch graph).

export interface Preset {
  key: string;
  title: string;
  blurb: string;
  build: (claimId: string) => FNOL;
  fixedId?: boolean; // the claim id is part of the scenario (the same claim every time)
}

export const SCALE_GRAPH = "claimgraph_scale";

